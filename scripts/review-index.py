#!/usr/bin/env python3
"""Keep the review registry (docs/review/) and its generated Copilot instructions in sync.

    python3 scripts/review-index.py          # regenerate the index and the Copilot files
    python3 scripts/review-index.py --check  # fail if anything is stale (CI, hooks)

Every `docs/review/<topic>.md` (except README.md) starts with frontmatter:

    ---
    title: Rust code
    applyTo: "**/*.rs"
    summary: One line shown in the index.
    ---

From those files the script generates:
  - the table between the markers in docs/review/README.md;
  - `.github/instructions/<topic>.instructions.md` for GitHub Copilot review (same body, applyTo kept).

`--check` also fails when none of a topic's applyTo globs match a git-tracked file (the rule
drifted away from the code); a single unmatched glob only warns (for example CHANGELOG.md
before the first release).
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

REVIEW_DIR = Path("docs/review")
INDEX = REVIEW_DIR / "README.md"
COPILOT_DIR = Path(".github/instructions")
START = "<!-- review-index:start (generated by scripts/review-index.py, do not edit) -->"
END = "<!-- review-index:end -->"
GENERATED = "<!-- generated from {source} by scripts/review-index.py; edit the source instead -->"
REQUIRED = ("title", "applyTo", "summary")


def parse_topic(path):
    """Return (frontmatter dict, body) of a topic file, or exit with a message."""
    text = path.read_text(encoding="utf-8")
    match = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)

    if not match:
        sys.exit(f"{path}: missing frontmatter")

    meta = {}

    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip().strip('"')

    missing = [key for key in REQUIRED if not meta.get(key)]

    if missing:
        sys.exit(f"{path}: frontmatter lacks {', '.join(missing)}")

    return meta, text[match.end():]


def glob_regex(pattern):
    """Translate a Copilot-style glob (`**`, `*`, `?`) into an anchored regex."""
    out, index = [], 0

    while index < len(pattern):
        if pattern.startswith("**/", index):
            out.append("(?:.*/)?")
            index += 3
        elif pattern.startswith("**", index):
            out.append(".*")
            index += 2
        elif pattern[index] == "*":
            out.append("[^/]*")
            index += 1
        elif pattern[index] == "?":
            out.append("[^/]")
            index += 1
        else:
            out.append(re.escape(pattern[index]))
            index += 1

    return re.compile("^" + "".join(out) + "$")


def unmatched_globs(apply_to, tracked):
    """Return the globs of an applyTo value that match no tracked file."""
    globs = [g.strip() for g in apply_to.split(",") if g.strip()]
    return [g for g in globs if not any(glob_regex(g).match(path) for path in tracked)]


def render_index(topics):
    """Return the generated index table."""
    rows = ["| Topic | Applies to | Summary |", "|---|---|---|"]

    for path, meta in topics:
        globs = ", ".join(f"`{g.strip()}`" for g in meta["applyTo"].split(","))
        rows.append(f"| [{meta['title']}]({path.name}) | {globs} | {meta['summary']} |")

    return "\n".join([START, "", *rows, "", END])


def render_copilot(path, meta, body):
    """Return the Copilot instruction file generated from one topic."""
    header = f'---\napplyTo: "{meta["applyTo"]}"\n---\n\n'
    return header + GENERATED.format(source=path.as_posix()) + "\n\n" + body.lstrip("\n")


def expected_files(topics_with_bodies):
    """Return {path: content} for every generated file."""
    index_text = INDEX.read_text(encoding="utf-8") if INDEX.exists() else f"# Review guide\n\n{START}\n{END}\n"

    if START not in index_text or END not in index_text:
        sys.exit(f"{INDEX}: missing the {START!r} / {END!r} markers")

    before, rest = index_text.split(START, 1)
    after = rest.split(END, 1)[1]
    topics = [(path, meta) for path, meta, _ in topics_with_bodies]
    files = {INDEX: before + render_index(topics) + after}

    for path, meta, body in topics_with_bodies:
        files[COPILOT_DIR / f"{path.stem}.instructions.md"] = render_copilot(path, meta, body)

    return files


def orphans(expected):
    """Return generated Copilot files whose source topic no longer exists."""
    if not COPILOT_DIR.exists():
        return []

    marker = "by scripts/review-index.py"
    return [
        path
        for path in COPILOT_DIR.glob("*.instructions.md")
        if path not in expected and marker in path.read_text(encoding="utf-8")
    ]


def check(expected, stale_orphans, drift):
    """Report every out-of-date file and drifted glob; return the problem count."""
    problems = [str(path) for path, content in expected.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
    problems = [f"{p}: out of date" for p in problems]
    problems += [f"{p}: generated file without a source topic" for p in stale_orphans]
    problems += drift

    for problem in problems:
        print(problem)

    if problems:
        print("run: python3 scripts/review-index.py")

    return len(problems)


def main():
    """Entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    if not REVIEW_DIR.is_dir():
        print(f"no {REVIEW_DIR}/ registry; nothing to do")
        return

    tracked = subprocess.check_output(["git", "ls-files"], text=True).splitlines()
    sources = sorted(p for p in REVIEW_DIR.glob("*.md") if p.name != "README.md")
    topics = [(path, *parse_topic(path)) for path in sources]
    drift, warnings = [], []

    for path, meta, _ in topics:
        globs = [g.strip() for g in meta["applyTo"].split(",") if g.strip()]
        unmatched = unmatched_globs(meta["applyTo"], tracked)

        if len(unmatched) == len(globs):
            drift.append(f"{path}: no applyTo glob matches a tracked file")
        else:
            warnings += [f"{path}: applyTo glob {g!r} matches no tracked file" for g in unmatched]

    for warning in warnings:
        print(f"warning: {warning}")

    expected = expected_files(topics)
    stale = orphans(expected)

    if args.check:
        sys.exit(1 if check(expected, stale, drift) else 0)

    COPILOT_DIR.mkdir(parents=True, exist_ok=True)

    for path, content in expected.items():
        path.write_text(content, encoding="utf-8")

    for path in stale:
        path.unlink()

    for problem in drift:
        print(f"error: {problem}")

    print(f"{len(topics)} topic(s) indexed")


if __name__ == "__main__":
    main()
